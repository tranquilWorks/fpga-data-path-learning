assertRejects(@() model(2,4,true,false),'P07:InvalidSelectedFrame');
assertRejects(@() model(2,4,3,2), ...
    'P07:InvalidBrokenFloorSchedule');
assertRejects(@() model(2,4,3,0.5), ...
    'P07:InvalidBrokenFloorSchedule');
assertRejects(@() model(2,4,3,[false true]), ...
    'P07:InvalidBrokenFloorSchedule');
assertRejects(@() model(2,4,3,NaN), ...
    'P07:InvalidBrokenFloorSchedule');
assertRejects(@() model(2,4,3,Inf), ...
    'P07:InvalidBrokenFloorSchedule');
assertRejects(@() model(2,4,3,1+1i), ...
    'P07:InvalidBrokenFloorSchedule');

selectedFirst = model(3,2,1,false);
selectedLast = model(3,2,6,false);
assert(isequal(selectedFirst.productCodeByFrame, ...
        selectedLast.productCodeByFrame) && ...
    isequal(selectedFirst.referenceIssueCycle, ...
        selectedLast.referenceIssueCycle) && ...
    isequal(selectedFirst.actualIssueCycle,selectedLast.actualIssueCycle) && ...
    isequal(selectedFirst.actualProductValidByFrame, ...
        selectedLast.actualProductValidByFrame) && ...
    isequal(selectedFirst.referenceQueuedFrameCount, ...
        selectedLast.referenceQueuedFrameCount), ...
    'P07:SelectedViewIsolation', ...
    'Selecting a frame must not alter scheduling or products.');
baselineAfterFailures = model(2,4,3,false);
maximumBroken = model(7,8,6,true); %#ok<NASGU>
baselineAfterOtherCall = model(2,4,3,false);
assert(isequaln(baseline,baselineAfterFailures) && ...
    isequaln(baseline,baselineAfterOtherCall), ...
    'P07:DeterminismRecovery', ...
    'Valid output must recover after failures and unrelated calls.');

disp(['P07 checks passed: products, capacity, demand, tail coverage, ' ...
    'validation, resource bounds, and recovery.']);
end

function assertRejects(thunk,expectedIdentifier)
rejectedAsExpected = false;
try
    thunk();
catch exception
    rejectedAsExpected = strcmp(exception.identifier,expectedIdentifier);
end
assert(rejectedAsExpected,'P07:MalformedInputAccepted', ...
    'Expected malformed input to raise %s.',expectedIdentifier);
end
