    'P07:InvalidOfferedFrameInterval');
assertRejects(@() model(2,true,3,false), ...
    'P07:InvalidOfferedFrameInterval');
assertRejects(@() model(2,4,0,false),'P07:InvalidSelectedFrame');
assertRejects(@() model(2,4,7,false),'P07:InvalidSelectedFrame');
assertRejects(@() model(2,4,2.5,false),'P07:InvalidSelectedFrame');
assertRejects(@() model(2,4,[2 3],false),'P07:InvalidSelectedFrame');
